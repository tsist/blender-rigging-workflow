"""Unexecuted self-owned limb candidate; fixed pole angle, no hidden IK seeds.

Only objects generated by create_module are accepted. Snap names describe the
source and destination: ik_to_fk means selector 1 -> 0; fk_to_ik means 0 -> 1.
No action/NLA/keying, arbitrary rig retrofit or human deformation claim.
"""
import json
import math
import re

import bpy
from mathutils import Matrix, Quaternion, Vector
from .collector import _all_ids, _constraints, _target_slots

TOLERANCE = 2e-4
EPS = 1e-8
SCHEMA = 'hrig.self_limb.p2.1'
TAG = 'hrig_module_id'
CHANNELS = ('location', 'rotation_euler', 'rotation_quaternion',
            'rotation_axis_angle', 'scale')


class Refused(ValueError):
    def __init__(self, code, message):
        self.code = code
        super().__init__(message)


def _plain(matrix):
    return [[float(x) for x in row] for row in matrix]


def _error(a, b):
    values = [abs(float(a[r][c]) - float(b[r][c]))
              for r in range(4) for c in range(4)]
    return max(values) if all(math.isfinite(x) for x in values) else math.inf


def _finite(matrix):
    if any(not math.isfinite(float(x)) for row in matrix for x in row):
        raise Refused('NONFINITE_MATRIX', 'Finite matrices are required')
    if matrix.to_3x3().determinant() <= 1e-12:
        raise Refused('NONPOSITIVE_MATRIX', 'Positive nonsingular transforms required')


def _refresh(context, rig):
    rig.update_tag()
    context.view_layer.update()
    graph = context.evaluated_depsgraph_get()
    evaluated = rig.evaluated_get(graph)
    if not evaluated.is_evaluated or evaluated.original != rig:
        raise Refused('NO_EVALUATED_RIG', 'Distinct evaluated rig required')
    return evaluated, graph


def _worlds(context, rig, names):
    evaluated, _ = _refresh(context, rig)
    answer = {}
    for name in names:
        matrix = (evaluated.matrix_world @ evaluated.pose.bones[name].matrix).copy()
        _finite(matrix)
        answer[name] = matrix
    return answer


def _channels(bone):
    return dict(rotation_mode=bone.rotation_mode,
                **{key: list(getattr(bone, key)) for key in CHANNELS})


def _restore(bone, state):
    bone.rotation_mode = state['rotation_mode']
    for key in CHANNELS:
        setattr(bone, key, state[key])


def _set_world(context, rig, name, world):
    """Own transform-only control; connected bones must match parent tail."""
    _finite(world)
    evaluated, _ = _refresh(context, rig)
    pb = rig.pose.bones[name]
    if pb.constraints:
        raise Refused('CONSTRAINED_DESTINATION', name)
    pose = evaluated.matrix_world.inverted() @ world
    args = {}
    if pb.parent:
        parent = evaluated.pose.bones[pb.parent.name]
        if pb.bone.use_connect and (pose.translation - parent.tail).length > TOLERANCE:
            raise Refused('CONNECTED_HEAD_MISMATCH', name)
        args = dict(parent_matrix=parent.matrix.copy(),
                    parent_matrix_local=pb.parent.bone.matrix_local.copy())
    basis = pb.bone.convert_local_to_pose(
        pose, pb.bone.matrix_local.copy(), invert=True, **args)
    _finite(basis)
    loc, rot, scale = basis.decompose()
    recomposed = Matrix.LocRotScale(loc, rot, scale)
    if _error(basis, recomposed) > TOLERANCE:
        raise Refused('UNREPRESENTABLE_BASIS', name)
    pb.matrix_basis = recomposed
    actual = _worlds(context, rig, [name])[name]
    if _error(actual, world) > TOLERANCE:
        raise Refused('CONTROL_WORLD_MISMATCH', name)


def _copy_constraint(owner, target, subtarget, kind='COPY_TRANSFORMS'):
    con = owner.constraints.new(kind)
    con.name = 'HRIG_' + kind + '_' + subtarget
    con.target = target
    con.subtarget = subtarget
    con.owner_space = 'POSE'
    con.target_space = 'POSE'
    if kind == 'COPY_TRANSFORMS':
        con.mix_mode = 'REPLACE'
    return con


def _mesh_positions(context, mesh):
    context.view_layer.update()
    evaluated = mesh.evaluated_get(context.evaluated_depsgraph_get())
    positions = [(evaluated.matrix_world @ vertex.co).copy()
                 for vertex in evaluated.data.vertices]
    if any(not math.isfinite(float(x)) for p in positions for x in p):
        raise Refused('NONFINITE_MESH', 'Evaluated mesh must be finite')
    return positions


def _mesh_error(first, second):
    if len(first) != len(second):
        return math.inf
    return max(((a - b).length for a, b in zip(first, second)), default=0.0)


def _witness_signature(mesh, rig):
    if len(mesh.data.vertices) != 12 or len(mesh.data.polygons) != 3 or mesh.data.shape_keys is not None:
        raise Refused('WITNESS_GEOMETRY_CHANGED','Expected exactly twelve vertices and three rigid witness quads')
    return {'vertices':[list(v.co) for v in mesh.data.vertices],
        'edges':[list(e.vertices) for e in mesh.data.edges],
        'polygons':[list(p.vertices) for p in mesh.data.polygons],
        'groups':[(g.name,g.index,g.lock_weight) for g in mesh.vertex_groups],
        'weights':[[(g.group,g.weight) for g in v.groups] for v in mesh.data.vertices],
        'deform_flags':{b.name:b.use_deform for b in rig.data.bones},
        'modifiers':[{'type':m.type,'show_viewport':m.show_viewport,'show_render':m.show_render,
                      'object':m.object.name if m.object else None,
                      'use_vertex_groups':m.use_vertex_groups,'use_bone_envelopes':m.use_bone_envelopes,
                      'preserve_volume':m.use_deform_preserve_volume} for m in mesh.modifiers]}


def _no_external_consumers(rig, mesh):
    ids = _all_ids()
    if ids is None:
        raise Refused('ID_BUDGET','Cannot verify the owned module consumer boundary')
    for owner in ids:
        ad = getattr(owner,'animation_data',None)
        if owner == rig or not ad:
            continue
        if any(t.id in (rig,mesh) for f in ad.drivers for v in f.driver.variables for t in v.targets):
            raise Refused('EXTERNAL_DRIVER_CONSUMER','Module is read by a foreign driver ID')
    for obj in bpy.data.objects:
        if obj in (rig,mesh):
            continue
        if obj.parent in (rig,mesh):
            raise Refused('EXTERNAL_PARENT_CONSUMER',obj.name)
        for modifier in obj.modifiers:
            for prop in modifier.bl_rna.properties:
                if prop.type == 'POINTER' and prop.fixed_type.identifier == 'Object' and getattr(modifier,prop.identifier) in (rig,mesh):
                    raise Refused('EXTERNAL_MODIFIER_CONSUMER',obj.name)
        for _,_,constraint in _constraints([obj]):
            if any(target in (rig,mesh) for _,target,_,_ in _target_slots(constraint)):
                raise Refused('EXTERNAL_CONSTRAINT_CONSUMER',obj.name)


def _chain_check(expected, actual, names):
    errors = {name: _error(expected[name], actual[name]) for name in names}
    if max(errors.values(), default=0.0) > TOLERANCE:
        raise Refused('CHAIN_MATRIX_MISMATCH', json.dumps(errors, sort_keys=True))
    return errors


def _snapshot(rig, settings):
    return {'channels': {pb.name: _channels(pb) for pb in rig.pose.bones},
            'selector': settings['ik_fk'],
            'ik': {pb.name: {c.name: {'mute': c.mute, 'influence': c.influence,
                                    'pole_angle': c.pole_angle}
                            for c in pb.constraints if c.type == 'IK'}
                   for pb in rig.pose.bones}}


def _rollback(context, rig, settings, state):
    settings['ik_fk'] = state['selector']
    for name, channels in state['channels'].items():
        _restore(rig.pose.bones[name], channels)
    for name, constraints in state['ik'].items():
        for cname, values in constraints.items():
            constraint = rig.pose.bones[name].constraints[cname]
            for key, value in values.items():
                setattr(constraint, key, value)
    _refresh(context, rig)
    return _snapshot(rig, settings) == state


def _module(context, manifest):
    if context.mode != 'OBJECT':
        raise Refused('OBJECT_MODE_REQUIRED', 'Only Object mode is supported')
    if not isinstance(manifest, dict) or manifest.get('schema') != SCHEMA:
        raise Refused('INVALID_MANIFEST', 'Expected self_limb manifest')
    rig = bpy.data.objects.get(manifest.get('rig', ''))
    mesh = bpy.data.objects.get(manifest.get('mesh', ''))
    if (rig is None or mesh is None or rig.type != 'ARMATURE' or mesh.type != 'MESH'
            or rig.get(TAG) != manifest.get('module_id')
            or mesh.get(TAG) != manifest.get('module_id')
            or rig.library or mesh.library or not rig.is_editable or not mesh.is_editable):
        raise Refused('MODULE_IDENTITY', 'Owned editable module objects required')
    names = manifest['bones']
    if rig.get('hrig_manifest') != json.dumps(manifest, ensure_ascii=False):
        raise Refused('MANIFEST_CHANGED', 'Stored creation manifest must match exactly')
    expected_names = set(names['FK'] + names['IK'] + names['DEF']
                         + [names['target'], names['pole'], names['settings']])
    if set(rig.pose.bones.keys()) != expected_names:
        raise Refused('MODULE_CHANGED', 'Declared bone set changed')
    for name in expected_names:
        if _error(rig.data.bones[name].matrix_local,
                  Matrix(manifest['rest_matrices'][name])) > 1e-7:
            raise Refused('REST_CHANGED', name)
        bone = rig.data.bones[name]
        structural = manifest['rest_structure'][name]
        if (abs(bone.length - structural['length']) > 1e-7
                or (bone.parent.name if bone.parent else None) != structural['parent']
                or bone.use_connect != structural['connected']
                or bone.inherit_scale != structural['inherit_scale']
                or bone.use_local_location != structural['local_location']
                or bone.use_inherit_rotation != structural['inherit_rotation']):
            raise Refused('REST_STRUCTURE_CHANGED', name)
    ad = rig.animation_data
    if ad and (ad.action or len(ad.nla_tracks)):
        raise Refused('ANIMATED_MODULE', 'Snap does not rewrite Action/NLA')
    if any(any(pb.lock_location) or (pb.lock_rotations_4d and pb.lock_rotation_w)
           or any(pb.lock_rotation) or any(pb.lock_scale) for pb in rig.pose.bones):
        raise Refused('LOCKED_MODULE', 'Module control locks changed')
    evaluated, _ = _refresh(context, rig)
    world = evaluated.matrix_world
    _finite(world)
    loc, rot, scale = world.decompose()
    if (min(scale) <= EPS or max(scale) - min(scale) > TOLERANCE
            or _error(world, Matrix.LocRotScale(loc, rot, scale)) > TOLERANCE):
        raise Refused('OBJECT_SCALE_DOMAIN', 'Positive uniform no-shear object transform required')
    settings = rig.pose.bones[names['settings']]
    if settings.get('ik_fk') not in (0.0, 1.0):
        raise Refused('NONENDPOINT_SELECTOR', 'Selector must be exactly 0 or 1')
    con = rig.pose.bones[names['IK'][1]].constraints.get(manifest['ik_constraint'])
    if (con is None or con.type != 'IK' or con.target != rig
            or con.subtarget != names['target'] or con.pole_target != rig
            or con.pole_subtarget != names['pole'] or con.pole_angle != 0.0
            or con.chain_count != 2 or con.use_stretch or con.use_rotation
            or not con.use_location or not con.use_tail or con.mute or con.influence != 1.0):
        raise Refused('IK_CONTRACT_CHANGED', 'Fixed-angle two-link Legacy IK required')
    if rig.pose.ik_solver != 'LEGACY':
        raise Refused('SOLVER_CHANGED', 'Legacy IK only')
    for name in names['FK'] + [names['target'], names['pole'], names['settings']]:
        if rig.pose.bones[name].constraints:
            raise Refused('CONTROL_CONSTRAINT_CHANGED', name)
    if rig.pose.bones[names['IK'][0]].constraints:
        raise Refused('UPPER_IK_CONSTRAINT_CHANGED', 'Upper IK must have no local constraints')
    if len(rig.pose.bones[names['IK'][1]].constraints) != 1:
        raise Refused('LOWER_IK_CONSTRAINT_CHANGED', 'Exactly one declared lower IK constraint required')
    end_constraints = list(rig.pose.bones[names['IK'][2]].constraints)
    if (len(end_constraints) != 1 or end_constraints[0].type != 'COPY_ROTATION'
            or end_constraints[0].target != rig
            or end_constraints[0].subtarget != names['target']
            or end_constraints[0].owner_space != 'POSE'
            or end_constraints[0].target_space != 'POSE'
            or end_constraints[0].mute or end_constraints[0].influence != 1.0):
        raise Refused('END_ORIENTATION_CHANGED', 'Declared independent end Copy Rotation required')
    for i, name in enumerate(names['DEF']):
        constraints = list(rig.pose.bones[name].constraints)
        if len(constraints) != 2:
            raise Refused('OUTPUT_CONSTRAINT_CHANGED', name)
        for j, chain in enumerate(('FK', 'IK')):
            c = constraints[j]
            if (c.type != 'COPY_TRANSFORMS' or c.target != rig
                    or c.subtarget != names[chain][i] or c.mute
                    or c.owner_space != 'POSE' or c.target_space != 'POSE'
                    or c.mix_mode != 'REPLACE' or (j == 0 and c.influence != 1.0)):
                raise Refused('OUTPUT_CONSTRAINT_CHANGED', name)
    for name in names['FK'] + names['IK']:
        if max(abs(float(v) - 1.0) for v in rig.pose.bones[name].scale) > TOLERANCE:
            raise Refused('BONE_SCALE_DOMAIN', 'Unit local chain scale required')
    expected_drivers = set(manifest['selector_driver_paths'])
    drivers = list(ad.drivers) if ad else []
    if len(drivers) != 3 or {fc.data_path for fc in drivers} != expected_drivers:
        raise Refused('DRIVER_CONTRACT_CHANGED', 'Exactly three declared DEF selector drivers required')
    prop_path = settings.path_from_id() + '["ik_fk"]'
    for fc in drivers:
        driver = fc.driver
        if (fc.mute or not driver.is_valid or driver.expression != 'switch' or len(driver.variables) != 1
                or driver.variables[0].name != 'switch'
                or driver.variables[0].type != 'SINGLE_PROP'
                or driver.variables[0].targets[0].id != rig
                or driver.variables[0].targets[0].data_path != prop_path):
            raise Refused('DRIVER_CONTRACT_CHANGED', fc.data_path)
    mods = list(mesh.modifiers)
    if len(mods) != 1 or mods[0].type != 'ARMATURE' or mods[0].object != rig:
        raise Refused('MESH_CONTRACT_CHANGED', 'Single owned Armature modifier required')
    signature = json.loads(json.dumps(_witness_signature(mesh,rig)))
    if signature != manifest['witness_signature']:
        raise Refused('WITNESS_CHANGED','Witness topology, weights, deform flags or modifier changed')
    _no_external_consumers(rig,mesh)
    return rig, mesh, settings, names


def create_module(context, spec):
    """Create independent editable limb and 12-vertex rigid witness quads.

    Returns {ok,manifest}. On native construction failure only newly created IDs
    are removed, and the caller's selection/active object are restored.
    """
    objects, datas = [], []
    before_active = context.view_layer.objects.active
    before_selected = list(context.selected_objects)
    try:
        if context.mode != 'OBJECT':
            raise Refused('OBJECT_MODE_REQUIRED', 'Creation requires Object mode')
        module_id = spec.get('module_id')
        if not isinstance(module_id, str) or not re.fullmatch(r'[A-Za-z0-9_-]{1,64}', module_id):
            raise Refused('INVALID_MODULE_ID', 'Use 1..64 ASCII letters/digits/_/-')
        if any(ob.get(TAG) == module_id for ob in bpy.data.objects):
            raise Refused('MODULE_EXISTS', module_id)
        side = spec.get('side', 1)
        roll = spec.get('rest_roll', 0.0)
        uniform = spec.get('object_uniform_scale', 1.0)
        if type(side) not in (int, float) or side not in (-1, 1):
            raise Refused('INVALID_SIDE', 'side must be -1 or 1')
        if (type(roll) not in (int, float) or not math.isfinite(roll)
                or type(uniform) not in (int, float) or not math.isfinite(uniform)
                or not 1e-3 <= uniform <= 1e3):
            raise Refused('INVALID_SPEC', 'Finite roll and positive scale within 1e-3..1e3 required')
        label = spec.get('name', module_id)
        if not isinstance(label, str) or not label or len(label) > 80:
            raise Refused('INVALID_NAME', 'Nonempty name <=80 characters required')
        arm = bpy.data.armatures.new(label + '_Armature')
        datas.append(arm)
        rig = bpy.data.objects.new(label + '_Rig', arm)
        objects.append(rig)
        context.collection.objects.link(rig)
        rig[TAG] = module_id
        rig.scale = (uniform,) * 3
        for ob in context.selected_objects:
            ob.select_set(False)
        rig.select_set(True)
        context.view_layer.objects.active = rig
        bpy.ops.object.mode_set(mode='EDIT')
        A = Vector((side * 0.4, 0.0, 0.0))
        B = Vector((side * 1.2, 0.2, 0.2))
        C = Vector((side * 2.0, 0.0, 0.0))
        D = C + Vector((side * 0.35, 0.0, 0.0))
        points = (A, B, C, D)
        rolls = (roll, -0.7 * roll + 0.23, 0.5 * roll)
        names = {}
        for chain in ('FK', 'IK', 'DEF'):
            names[chain] = [chain + suffix for suffix in ('Upper', 'Lower', 'End')]
            parent = None
            for i, name in enumerate(names[chain]):
                bone = arm.edit_bones.new(name)
                bone.head, bone.tail = points[i], points[i + 1]
                bone.roll = rolls[i]
                bone.use_deform = chain == 'DEF'
                if parent:
                    bone.parent = parent
                    bone.use_connect = i == 1
                parent = bone
        names.update(target='Target', pole='Pole', settings='Settings')
        for key, position in (('target', C), ('pole', A + Vector((0, 0, 1.5))),
                              ('settings', A + Vector((0, -0.5, 0)))):
            bone = arm.edit_bones.new(names[key])
            bone.head = position
            bone.tail = position + (D - C)
            bone.roll = rolls[2] if key == 'target' else 0.0
            bone.use_deform = False
        bpy.ops.object.mode_set(mode='OBJECT')
        for pb in rig.pose.bones:
            pb.rotation_mode = 'QUATERNION'
        rig.pose.ik_solver = 'LEGACY'
        settings = rig.pose.bones[names['settings']]
        settings['ik_fk'] = 0.0
        settings.id_properties_ui('ik_fk').update(min=0.0, max=1.0)
        lower = rig.pose.bones[names['IK'][1]]
        ik = lower.constraints.new('IK')
        ik.name = 'HRIG_TWO_LINK_IK'
        ik.target, ik.subtarget = rig, names['target']
        ik.pole_target, ik.pole_subtarget = rig, names['pole']
        ik.chain_count, ik.iterations = 2, 128
        ik.pole_angle, ik.use_stretch = 0.0, False
        ik.use_tail, ik.use_location, ik.use_rotation = True, True, False
        for name in names['IK']:
            rig.pose.bones[name].ik_stretch = 0.0
        _copy_constraint(rig.pose.bones[names['IK'][2]], rig,
                         names['target'], 'COPY_ROTATION')
        paths = []
        for i, name in enumerate(names['DEF']):
            _copy_constraint(rig.pose.bones[name], rig, names['FK'][i])
            con = _copy_constraint(rig.pose.bones[name], rig, names['IK'][i])
            fc = con.driver_add('influence')
            fc.driver.type = 'SCRIPTED'
            var = fc.driver.variables.new()
            var.name, var.type = 'switch', 'SINGLE_PROP'
            var.targets[0].id = rig
            var.targets[0].data_path = settings.path_from_id() + '["ik_fk"]'
            fc.driver.expression = 'switch'
            paths.append(fc.data_path)
        _refresh(context, rig)
        rest = {name: _plain(b.matrix_local) for name, b in arm.bones.items()}
        structure = {name: {'length': b.length,
                            'parent': b.parent.name if b.parent else None,
                            'connected': b.use_connect,
                            'inherit_scale': b.inherit_scale,
                            'local_location': b.use_local_location,
                            'inherit_rotation': b.use_inherit_rotation}
                     for name, b in arm.bones.items()}
        # Pole from upper X (alpha=0), using rest upper pose in the rig frame.
        up = arm.bones[names['IK'][0]].matrix_local.to_3x3().col[0]
        axis = (C - A).normalized()
        q = up - axis * up.dot(axis)
        if q.length <= EPS:
            raise Refused('REST_POLE_SINGULAR', 'Upper X projection is singular')
        pole_world = _worlds(context, rig, [names['pole']])[names['pole']]
        pole_world.translation = rig.matrix_world @ (A + 1.5 * q.normalized())
        _set_world(context, rig, names['pole'], pole_world)
        vertices, faces = [], []
        for i, name in enumerate(names['DEF']):
            midpoint = (points[i] + points[i + 1]) * 0.5
            along = (points[i + 1] - points[i]).normalized() * 0.18
            across = Vector((0, 0, 0.06))
            base = len(vertices)
            vertices.extend(tuple(midpoint + a * along + b * across)
                            for a, b in ((-1, -1), (1, -1), (1, 1), (-1, 1)))
            faces.append(tuple(base + j for j in range(4)))
        md = bpy.data.meshes.new(label + '_WitnessMesh')
        datas.append(md)
        md.from_pydata(vertices, [], faces)
        md.update()
        mesh = bpy.data.objects.new(label + '_Witness', md)
        objects.append(mesh)
        context.collection.objects.link(mesh)
        mesh[TAG] = module_id
        mesh.matrix_world = rig.matrix_world.copy()
        for i, name in enumerate(names['DEF']):
            group = mesh.vertex_groups.new(name=name)
            group.add(list(range(i * 4, i * 4 + 4)), 1.0, 'REPLACE')
        mod = mesh.modifiers.new('HRIG_Armature', 'ARMATURE')
        mod.object = rig
        manifest = {'schema': SCHEMA, 'module_id': module_id,
                    'rig': rig.name, 'mesh': mesh.name, 'bones': names,
                    'ik_constraint': ik.name, 'pole_angle': 0.0,
                    'selector_driver_paths': paths, 'rest_matrices': rest,
                    'rest_structure': structure,
                    'tolerance': TOLERANCE, 'side': side, 'rest_roll': roll,
                    'object_uniform_scale': uniform,
                    'scope': 'self-owned current-pose limb; no IK seeding; no keys',
                    'mesh_role': '12-vertex rigid witness quads, no human quality claim'}
        manifest['witness_signature'] = json.loads(json.dumps(_witness_signature(mesh,rig)))
        rig['hrig_manifest'] = json.dumps(manifest, ensure_ascii=False)
        # Creation only certifies the initial FK path; both snap directions must
        # be exercised externally before calling this a validated limb module.
        actual = _worlds(context, rig, names['FK'] + names['DEF'])
        errors = {names['DEF'][i]: _error(actual[names['DEF'][i]], actual[names['FK'][i]])
                  for i in range(3)}
        if max(errors.values()) > TOLERANCE:
            raise Refused('INITIAL_FK_OUTPUT_MISMATCH', str(errors))
        _mesh_positions(context, mesh)
        return {'ok': True, 'operation': 'create_module', 'manifest': manifest,
                'initial_fk_output_errors': errors,
                'ik_snap_validation': 'not_run'}
    except Exception as error:
        if context.mode == 'EDIT_ARMATURE' and context.view_layer.objects.active in objects:
            bpy.ops.object.mode_set(mode='OBJECT')
        for ob in reversed(objects):
            bpy.data.objects.remove(ob, do_unlink=True)
        for data in reversed(datas):
            if data.users == 0:
                if isinstance(data, bpy.types.Armature):
                    bpy.data.armatures.remove(data)
                elif isinstance(data, bpy.types.Mesh):
                    bpy.data.meshes.remove(data)
        return {'ok': False, 'operation': 'create_module',
                'error': {'code': getattr(error, 'code', 'NATIVE_ERROR'), 'message': str(error)},
                'created_ids_removed': True}
    finally:
        if context.mode == 'OBJECT':
            for ob in context.selected_objects:
                ob.select_set(False)
            for ob in before_selected:
                if ob.name in context.view_layer.objects:
                    ob.select_set(True)
            if before_active and before_active.name in context.view_layer.objects:
                context.view_layer.objects.active = before_active
            else:
                context.view_layer.objects.active = None


def _snap(context, manifest, source_mode):
    operation = 'snap_ik_to_fk' if source_mode == 1 else 'snap_fk_to_ik'
    rig = settings = snapshot = before = mesh_before = None
    diagnostics = None
    try:
        rig, mesh, settings, names = _module(context, manifest)
        if settings['ik_fk'] != source_mode:
            raise Refused('WRONG_SOURCE_MODE', 'Explicit source selector endpoint required')
        snapshot = _snapshot(rig, settings)
        before = _worlds(context, rig, names['DEF'])
        mesh_before = _mesh_positions(context, mesh)
        source_names = names['IK'] if source_mode == 1 else names['FK']
        source = _worlds(context, rig, source_names)
        for i in range(3):
            if _error(source[source_names[i]], before[names['DEF'][i]]) > TOLERANCE:
                raise Refused('SOURCE_OUTPUT_MISMATCH', source_names[i])
        if source_mode == 1:
            for index, target in enumerate(names['FK']):
                _set_world(context, rig, target, source[source_names[index]])
        else:
            evaluated, _ = _refresh(context, rig)
            rw = evaluated.matrix_world.copy()
            upper_pose = rw.inverted() @ source[source_names[0]]
            lower_pose = rw.inverted() @ source[source_names[1]]
            A = upper_pose.translation.copy()
            C = lower_pose @ Vector((0, rig.data.bones[source_names[1]].length, 0))
            axis = C - A
            if axis.length <= EPS:
                raise Refused('FOLDED_SINGULARITY', 'Root and endpoint coincide')
            axis.normalize()
            root_x = upper_pose.to_3x3().col[0].normalized()
            q = root_x - axis * root_x.dot(axis)
            if q.length <= EPS:
                raise Refused('POLE_SINGULARITY', 'Fixed alpha upper-X projection is singular')
            bend = lower_pose.translation - A
            bend -= axis * bend.dot(axis)
            if bend.length <= 1e-5:
                raise Refused('STRAIGHT_SINGULARITY', 'Near-straight limb outside snap domain')
            distance = sum(rig.data.bones[name].length for name in names['IK'][:2])
            pole_world = _worlds(context, rig, [names['pole']])[names['pole']]
            pole_world.translation = rw @ (A + distance * q.normalized())
            _set_world(context, rig, names['target'], source[source_names[2]])
            _set_world(context, rig, names['pole'], pole_world)
            # No IK bone basis, angle, constraint or solver seed is changed.
            ik_actual = _worlds(context, rig, names['IK'])
            # Legacy constrains the pole before its Jacobian iterations, not
            # after them. The final upper X is therefore only an initial pole
            # guess. Measure its azimuth after a native solve and correct the
            # pole once, using rotation covariance about the fixed goal axis.
            # Full-matrix verification below still rejects unrepresentable FK.
            actual_pose = rw.inverted() @ ik_actual[names['IK'][0]]
            actual_x = actual_pose.to_3x3().col[0].normalized()
            actual_q = actual_x - axis * actual_x.dot(axis)
            if actual_q.length <= EPS:
                raise Refused('SOLVED_POLE_SINGULARITY', 'Native upper X projection is singular')
            a, b = actual_q.normalized(), q.normalized()
            correction = math.atan2(axis.dot(a.cross(b)), a.dot(b))
            corrected = Quaternion(axis, correction) @ q.normalized()
            pole_world.translation = rw @ (A + distance * corrected)
            _set_world(context, rig, names['pole'], pole_world)
            ik_actual = _worlds(context, rig, names['IK'])
            diagnostics = {'matrix_errors': {names['IK'][i]: _error(ik_actual[names['IK'][i]], source[source_names[i]]) for i in range(3)},
                'desired_world': {names['IK'][i]: _plain(source[source_names[i]]) for i in range(3)},
                'actual_world': {n:_plain(m) for n,m in ik_actual.items()},
                'initial_pole_pose': list(A + distance*q.normalized()),
                'pole_pose': list(A + distance*corrected), 'root_pose': list(A),
                'end_pose': list(C), 'axis': list(axis), 'upper_x': list(root_x),
                'native_pole_azimuth_correction': correction, 'native_pole_solves': 2}
            for i in range(3):
                if _error(ik_actual[names['IK'][i]], source[source_names[i]]) > TOLERANCE:
                    raise Refused('IK_UNREPRESENTABLE_FK', 'Target/pole do not reproduce full FK matrices')
        settings['ik_fk'] = float(1 - source_mode)
        after = _worlds(context, rig, names['DEF'])
        errors = _chain_check(before, after, names['DEF'])
        mesh_delta = _mesh_error(mesh_before, _mesh_positions(context, mesh))
        if not math.isfinite(mesh_delta) or mesh_delta > TOLERANCE:
            raise Refused('MESH_SNAP_MISMATCH', str(mesh_delta))
        if rig.pose.bones[names['IK'][1]].constraints[manifest['ik_constraint']].pole_angle != 0.0:
            raise Refused('POLE_ANGLE_CHANGED', 'Fixed alpha must remain zero')
        return {'ok': True, 'operation': operation, 'module_id': manifest['module_id'],
                'source_mode': source_mode, 'target_mode': 1 - source_mode,
                'output_world_errors': errors, 'mesh_world_max_distance': mesh_delta,
                'before_output_world': {name: _plain(value) for name, value in before.items()},
                'after_output_world': {name: _plain(value) for name, value in after.items()},
                'pole_angle': 0.0, 'ik_basis_seeded': False,
                'diagnostics': diagnostics, 'tolerance': TOLERANCE}
    except Exception as error:
        restored = snapshot is None
        rollback_error = None
        if snapshot is not None:
            try:
                restored = _rollback(context, rig, settings, snapshot)
                if before is not None:
                    restored_world = _worlds(context, rig, names['DEF'])
                    restored = restored and all(_error(before[n], restored_world[n]) <= TOLERANCE
                                                for n in names['DEF'])
                if mesh_before is not None:
                    restored = restored and _mesh_error(
                        mesh_before, _mesh_positions(context, mesh)) <= TOLERANCE
            except Exception as rollback:
                restored, rollback_error = False, str(rollback)
        return {'ok': False, 'operation': operation,
                'error': {'code': getattr(error, 'code', 'NATIVE_ERROR'), 'message': str(error)},
                'channels_selector_solver_restored': restored,
                'rollback_error': rollback_error, 'diagnostics': diagnostics, 'tolerance': TOLERANCE}


def snap_ik_to_fk(context, manifest):
    """Match evaluated IK to FK then switch 1 -> 0, or restore state."""
    return _snap(context, manifest, 1)


def snap_fk_to_ik(context, manifest):
    """Match FK using Target/Pole only then switch 0 -> 1; no hidden seeds."""
    return _snap(context, manifest, 0)


def inspect_module(context, manifest):
    """Validate the owned-module contract without editing channels or selector.

    Native dependency evaluation can occur; this does not certify arbitrary
    rigs, animation, human deformation quality or realtime performance.
    """
    try:
        rig, mesh, settings, names = _module(context, manifest)
        return {'ok': True, 'module_id': manifest['module_id'],
                'rig': rig.name, 'mesh': mesh.name, 'selector': settings['ik_fk']}
    except Exception as error:
        return {'ok': False, 'error': {'code': getattr(error, 'code', 'NATIVE_ERROR'),
                                      'message': str(error)}}
